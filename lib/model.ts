// Token Launch Radar — value model, radar-2.
//
// The board ranks protocols that record no token, by an implied value derived only from the
// sealed snapshot's own figures. Nothing here names a protocol: the same functions score every
// row, and the dashboard names them so a reader can check the arithmetic.
//
//   impliedValue(p) = tvl_usd x categoryPeerMultiple(p.category)
//                     x growthMultiplier(p.change_7d)
//                     x maturityMultiplier(ageDays(p.listed_at))
//
// categoryPeerMultiple(category) is the median market-cap / TVL ratio of the protocols in the
// SAME category whose token already trades (live-token peers). A lending protocol is therefore
// priced like lending protocols trade, a DEX like DEXes trade — not at one flat multiple for
// every category. With fewer than 3 live peers in a category it falls back to the global median
// across all live-token protocols, so no category is ever priced from a single outlier. The
// multiple is clamped to [0.02, 1.5] so one frothy category cannot explode the board.
//
// growthMultiplier clamps the 7-day TVL change to [-60, +120] % and applies half of it, so a
// fast-growing protocol outranks a shrinking one of the same size, but growth alone never
// doubles or halves a value.
//
// maturityMultiplier grows with ageDays — the days since DefiLlama first listed the protocol —
// from 0.6 for a brand-new listing to 1.0 at 3 years. A protocol that has run a long time with
// no token on record has had longer to build the usage a launch would price; an unknown
// listing date counts as 365 days. Age is the time with no token, not a prediction that a
// token is coming: the board says "records no token", never "has no token".
//
// Separation: isPreToken / isLiveToken split the snapshot in two. The ranked board holds only
// pre-token rows. Live-token protocols are never ranked; liveRows() lists them separately with
// their market cap — the market's own value, not a model's — so the judge can see the split.

